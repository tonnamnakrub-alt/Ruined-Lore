// รหัสประจำแพตช์ที่ไม่ซ้ำกัน — id อย่างเดียวไม่พอเพราะทุกแพตช์ย่อยใช้ "0.1" เหมือนกัน
export function patchKey(p) {
  return p.id + "-" + (p.rev || "");
}
