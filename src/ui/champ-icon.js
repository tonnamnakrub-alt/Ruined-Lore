// ทุกตัวต้องมีไอคอน ถ้าเพิ่มตัวใหม่แล้วลืมใส่ ให้ใช้วงกลมทึบไปก่อน
// จะได้ไม่พังหน้าจอ แต่ก็เห็นชัดว่ายังไม่ได้ทำ
const FALLBACK = [{ ring: [12, 12, 8, 2.4] }, { c: [12, 12, 3] }];

export const iconOf = (id) => CHAMP_ICON[id] || FALLBACK;


// ---------------------------------------------------------------
// วาดลง canvas — ใช้ในสนาม
// cx, cy = จุดกึ่งกลาง · size = ความกว้างเต็มของไอคอน
// ---------------------------------------------------------------
export function drawChampIcon(ctx, id, cx, cy, size, color, bg) {
  const k = size / 24;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(k, k);
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  for (const s of iconOf(id)) {
    const col = s.cut ? (bg || "#0B1220") : color;
    ctx.fillStyle = col;
    ctx.strokeStyle = col;
    if (s.c) {
      ctx.beginPath(); ctx.arc(s.c[0], s.c[1], s.c[2], 0, Math.PI * 2); ctx.fill();
    } else if (s.ring) {
      ctx.lineWidth = s.ring[3];
      ctx.beginPath(); ctx.arc(s.ring[0], s.ring[1], s.ring[2], 0, Math.PI * 2); ctx.stroke();
    } else if (s.r) {
      roundRect(ctx, s.r[0], s.r[1], s.r[2], s.r[3], s.r[4], s.rot);
      ctx.fill();
    } else if (s.p) {
      ctx.beginPath();
      s.p.forEach((pt, i) => (i ? ctx.lineTo(pt[0], pt[1]) : ctx.moveTo(pt[0], pt[1])));
      ctx.closePath(); ctx.fill();
    } else if (s.a) {
      ctx.lineWidth = s.a[5];
      ctx.beginPath();
      ctx.arc(s.a[0], s.a[1], s.a[2], (s.a[3] * Math.PI) / 180, (s.a[4] * Math.PI) / 180);
      ctx.stroke();
    } else if (s.l) {
      ctx.lineWidth = s.w;
      ctx.beginPath();
      s.l.forEach((pt, i) => (i ? ctx.lineTo(pt[0], pt[1]) : ctx.moveTo(pt[0], pt[1])));
      ctx.stroke();
    }
  }
  ctx.restore();
}

function roundRect(ctx, x, y, w, h, rx, rot) {
  const r = Math.min(rx || 0, w / 2, h / 2);
  ctx.save();
  if (rot) { ctx.translate(x + w / 2, y + h / 2); ctx.rotate((rot * Math.PI) / 180); ctx.translate(-w / 2, -h / 2); x = 0; y = 0; }
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y); ctx.quadraticCurveTo(x + w, y, x + w, y + r);
  ctx.lineTo(x + w, y + h - r); ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  ctx.lineTo(x + r, y + h); ctx.quadraticCurveTo(x, y + h, x, y + h - r);
  ctx.lineTo(x, y + r); ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
  ctx.restore();
}


// ---------------------------------------------------------------
// แปลงเป็นชิ้นส่วน SVG — ใช้ในเมนู (ฝั่ง React ห่อให้อีกทีใน kit.jsx)
// คืนอาเรย์ของ { tag, attrs } เพื่อไม่ต้องผูกกับ JSX ในไฟล์ .js
// ---------------------------------------------------------------
export function iconSvgParts(id, color, bg) {
  const out = [];
  const arcPath = (x, y, r, a0, a1) => {
    const p0 = [x + r * Math.cos((a0 * Math.PI) / 180), y + r * Math.sin((a0 * Math.PI) / 180)];
    const p1 = [x + r * Math.cos((a1 * Math.PI) / 180), y + r * Math.sin((a1 * Math.PI) / 180)];
    const sweep = ((a1 - a0 + 360) % 360) > 180 ? 1 : 0;
    return `M${p0[0].toFixed(2)} ${p0[1].toFixed(2)} A${r} ${r} 0 ${sweep} 1 ${p1[0].toFixed(2)} ${p1[1].toFixed(2)}`;
  };
  for (const s of iconOf(id)) {
    const color2 = s.cut ? (bg || "#0E1626") : color;
    if (s.c) out.push({ tag: "circle", attrs: { cx: s.c[0], cy: s.c[1], r: s.c[2], fill: color2 } });
    else if (s.ring) out.push({ tag: "circle", attrs: { cx: s.ring[0], cy: s.ring[1], r: s.ring[2], fill: "none", stroke: color2, strokeWidth: s.ring[3] } });
    else if (s.r) {
      const a = { x: s.r[0], y: s.r[1], width: s.r[2], height: s.r[3], rx: s.r[4], fill: color2 };
      if (s.rot) a.transform = `rotate(${s.rot} ${s.r[0] + s.r[2] / 2} ${s.r[1] + s.r[3] / 2})`;
      out.push({ tag: "rect", attrs: a });
    } else if (s.p) out.push({ tag: "polygon", attrs: { points: s.p.map((q) => q.join(",")).join(" "), fill: color2 } });
    else if (s.a) out.push({ tag: "path", attrs: { d: arcPath(s.a[0], s.a[1], s.a[2], s.a[3], s.a[4]), fill: "none", stroke: color2, strokeWidth: s.a[5], strokeLinecap: "round" } });
    else if (s.l) out.push({ tag: "path", attrs: { d: "M" + s.l.map((q) => q.join(" ")).join(" L"), fill: "none", stroke: color2, strokeWidth: s.w, strokeLinecap: "round", strokeLinejoin: "round" } });
  }
  return out;
}
